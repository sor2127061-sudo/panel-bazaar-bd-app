let currentLang = localStorage.getItem('pbbd_lang') || 'bn'

export function getLang() {
  return currentLang
}

export function setLang(l) {
  currentLang = l
  localStorage.setItem('pbbd_lang', l)
  document.documentElement.lang = l
}

export function t(key, vars = {}) {
  const str = translations[currentLang]?.[key] || translations.bn[key] || key
  return str.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? `{${k}}`)
}

export function useLang() {
  return currentLang
}
